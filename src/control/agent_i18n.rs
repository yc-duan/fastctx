macro_rules! agent_messages {
    ($title:expr, $tools:expr, $budget:expr, $config:expr, $guidance:expr,
     $receipt:expr, $absent:expr, $connected:expr, $attention:expr,
     $permission:expr, $error:expr, $shell:expr, $unsaved:expr,
     $apply:expr, $disconnect:expr, $doctor:expr, $leave:expr,
     $cancel:expr, $discard:expr, $save:expr, $empty:expr, $restart:expr) => {
        AgentMessages {
            title: $title,
            tools_title: $tools,
            effective_budget: $budget,
            config_path: $config,
            guidance_path: $guidance,
            receipt: $receipt,
            not_connected: $absent,
            connected: $connected,
            needs_attention: $attention,
            permission_denied: $permission,
            error: $error,
            shell_suite: $shell,
            unsaved: $unsaved,
            apply: $apply,
            disconnect: $disconnect,
            doctor: $doctor,
            leave_prompt: $leave,
            cancel: $cancel,
            discard: $discard,
            save_apply: $save,
            empty_set: $empty,
            restart_notice: $restart,
        }
    };
}

