/** Claude Code's own read of a file, its lines numbered as it gives them;
 *  the file is held on the specimen machine as it was read. */
export function readCall(machine: string, path: string, lines: readonly string[]): Partial<Tool> & { name: string; does: Tool["does"] } {
  keepFile(path, () => [...lines]);
  return {
    name: "Read",
    machine,
    input: { file_path: path },
    output: text(lines.map((line, at) => `${String(at + 1).padStart(6)}→${line}`).join("\n")),
    does: { as: "call" },
    duration_ms: 30,
  };
}
